// Write the deterministic canonical package and a human-readable import report.
// Nothing volatile (timestamps, absolute paths, machine names) is written into the
// compared content: two runs on unchanged sources must produce identical bytes.

import { mkdir, writeFile } from "node:fs/promises"
import { resolve } from "node:path"

function sortKeysRecursive(value) {
  if (value === null || typeof value !== "object") return value
  if (Array.isArray(value)) return value.map(sortKeysRecursive)
  const out = {}
  for (const key of Object.keys(value).sort()) out[key] = sortKeysRecursive(value[key])
  return out
}

export async function writeCanonicalPackage(pkg, outDir) {
  const dir = resolve(outDir)
  await mkdir(dir, { recursive: true })
  const path = resolve(dir, "canonical.json")
  await writeFile(path, `${JSON.stringify(sortKeysRecursive(pkg), null, 2)}\n`, "utf8")
  return path
}

export async function writeImportReport(report, outDir) {
  const dir = resolve(outDir)
  await mkdir(dir, { recursive: true })
  const path = resolve(dir, "import-report.md")
  await writeFile(path, renderMarkdown(report), "utf8")
  return path
}

const row = (cells) => `| ${cells.join(" | ")} |`

export function renderMarkdown(r) {
  const lines = []
  lines.push("# Ingest Import Report", "")
  lines.push(`Schema version: **${r.schemaVersion}**`, "")
  lines.push("This report is generated by `src/ingest`. It records what was read, what was", 
             "normalized, what is blocking, and what still needs an owner decision.", "")

  lines.push("## Sources", "")
  lines.push(row(["File", "Format", "Sheet", "sha256 (first 16)"]))
  lines.push(row(["---", "---", "---", "---"]))
  for (const s of r.sources) {
    lines.push(row([s.file, s.format, s.sheet ?? "—", (s.sha256 || "").slice(0, 16) || "—"]))
  }
  lines.push("")

  lines.push("## Entity counts", "")
  lines.push(row(["Entity", "Count", "Expected"]))
  lines.push(row(["---", "---", "---"]))
  for (const [key, value] of Object.entries(r.counts)) {
    const exp = r.expectedCounts?.[key]
    lines.push(row([key, String(value), exp === undefined || exp === null ? "—" : String(exp)]))
  }
  lines.push("")
  lines.push(`Rule coverage: **${r.coverage.hardRules}** hard rules (H1–H20) + ` +
             `**${r.coverage.systemRules}** system rules (S1–S2).`, "")

  lines.push("## Period totals per level", "")
  lines.push("Derived = sum of the subject periods each group must attend (all groups take all",
             "subjects). Printed = the figure the workbook states, where one exists.", "")
  lines.push(row(["Level", "Subjects", "Derived periods/group", "Printed total", "Status"]))
  lines.push(row(["---", "---", "---", "---", "---"]))
  for (const l of r.levels) {
    const status = l.printedTotal === null ? "no printed total"
      : l.printedTotal === l.derivedPeriods ? "matches"
      : l.printedTotal === 50 && l.derivedPeriods === 36 ? "MISMATCH (open question Q1)"
      : `MISMATCH (+${l.printedTotal - l.derivedPeriods})`
    lines.push(row([l.levelId, String(l.subjects), String(l.derivedPeriods), l.printedTotal ?? "—", status]))
  }
  lines.push("")

  lines.push("## Fixed pins (from ข้อกำหนด)", "")
  if (r.pins.length) {
    lines.push(row(["Level", "Subject", "Day", "Periods", "Room"]))
    lines.push(row(["---", "---", "---", "---", "---"]))
    for (const p of r.pins) {
      lines.push(row([p.levelId, `${p.id} ${p.name}`, p.day, `${p.startPeriod}–${p.endPeriod}`, p.roomLabel ?? p.roomClass]))
    }
  } else {
    lines.push("_No pins found._")
  }
  lines.push("")

  lines.push("## Teachers", "")
  lines.push(row(["ID", "Name", "Role", "Department band", "Unavailable"]))
  lines.push(row(["---", "---", "---", "---", "---"]))
  for (const t of r.teachers) {
    const band = t.minDepartmentHours === null ? "—" : `${t.minDepartmentHours}–${t.maxDepartmentHours} h`
    const una = t.unavailability.length
      ? t.unavailability.map((u) => `${u.day} ${u.startPeriod}–${u.endPeriod}`).join("; ")
      : "—"
    lines.push(row([t.id, t.name, `${t.role} (${t.roleLabelTh})`, band, una]))
  }
  lines.push("")
  lines.push("_The workbook assigns no subjects to teachers, so no teacher↔subject links exist in",
             "this package. The engine must treat that as an explicit decision (Q2)._", "")

  lines.push("## Normalizations applied", "")
  if (r.normalizations.length) {
    for (const n of r.normalizations) {
      lines.push(`- **${n.kind}**: \`${n.from}\` → \`${n.to}\`  (${n.sourceRef.sheet} row ${n.sourceRef.row})`)
    }
  } else {
    lines.push("_No normalizations were necessary._")
  }
  lines.push("")

  lines.push("## Blocking errors", "")
  if (r.errors.length) for (const e of r.errors) lines.push(`- **[${e.code}]** ${e.message}`)
  else lines.push("_None._")
  lines.push("")

  lines.push("## Warnings", "")
  if (r.warnings.length) for (const w of r.warnings) lines.push(`- **[${w.code}]** ${w.message}`)
  else lines.push("_None._")
  lines.push("")

  lines.push("## Guideline text checks", "")
  lines.push(`- ${r.guidelineChecks.message}`)
  if (r.guidelineChecks.missingPhrases?.length) {
    lines.push(`- Missing anchors: ${r.guidelineChecks.missingPhrases.join(", ")}`)
  }
  lines.push("")

  lines.push("## Unresolved questions for the owner", "")
  for (const q of r.unresolvedQuestions) {
    lines.push(`- **${q.id}** — ${q.question}`)
    if (q.blocks?.length) lines.push(`  - blocks: ${q.blocks.join(", ")}`)
  }
  lines.push("")
  return lines.join("\n")
}
